#pragma once

#ifndef JOB_H
#define JOB_H

namespace loki
{

namespace util
{

enum EJobState
{
	JS_PENDING = 0,
	JS_RUNNING,
	JS_DONE
};

class LkJob;
typedef std::list<LkJob*> JobList;
typedef unsigned int JobID;

class LkJob
{
public:
	LkJob();
	virtual ~LkJob();

	//////////////////////////////////////////////////////////////////////////
	// Adds a dependency to the job. Jobs that have dependencies will not
	// be started until all dependencies have completed.
	//////////////////////////////////////////////////////////////////////////
	void AddDependency( LkJob* _Dependency );

	//////////////////////////////////////////////////////////////////////////
	// Reset the state of the job so that it can be re-submitted to the job-
	// manager.
	//////////////////////////////////////////////////////////////////////////
	void Reset();
	
	//////////////////////////////////////////////////////////////////////////
	// Gets the state of the job.
	//////////////////////////////////////////////////////////////////////////
	EJobState GetState();

	//////////////////////////////////////////////////////////////////////////
	// The thread calling this function will either wait until the job is
	// finished if no arguments are specified, or wait for a certain amount
	// of time (or until the job is finished).
	//////////////////////////////////////////////////////////////////////////
	void WaitForJob( unsigned long _Ms = INFINITE );
protected:
	//////////////////////////////////////////////////////////////////////////
	// Returns the job's ID. Can be accessed by child classes.
	//////////////////////////////////////////////////////////////////////////
	JobID GetJobID();
private:
	friend class LkJobManager;

	//////////////////////////////////////////////////////////////////////////
	// The JobMain function is the function that should contain the code
	// that the job is designed to execute.
	// It is called by _JobMainWrapper by the job manager.
	//////////////////////////////////////////////////////////////////////////
	virtual void JobMain() = 0;

	//////////////////////////////////////////////////////////////////////////
	// This is called by the job manager. It provides functionality such as 
	// logging before and after the main job function is executed.
	//////////////////////////////////////////////////////////////////////////
	void _JobMainWrapper();

	//////////////////////////////////////////////////////////////////////////
	// Checks all dependencies to see whether the job can start.
	//////////////////////////////////////////////////////////////////////////
	bool _CanStart();

	EJobState m_State;
	JobList m_Dependencies;
	JobID m_ID;
	HANDLE m_EventDone;
};

}

}

#endif