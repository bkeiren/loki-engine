#pragma once

#ifndef CSVPARSER_H
#define CSVPARSER_H

#include <vector>
#include <string>

namespace loki
{

namespace util
{

class LkCSVParser
{
public:
	class LkCSVDataTable;

	LkCSVParser();
	~LkCSVParser();

	static LkCSVDataTable* ParseFile( const char* _File );
private:
};

class LkCSVParser::LkCSVDataTable
{
	friend class LkCSVParser;
public:
	LkCSVDataTable();
	~LkCSVDataTable();

	//////////////////////////////////////////////////////////////////////////
	// Get data from the table at position [_Column (X), _Row (Y)].
	// Returns false if the indices are outside of the table's range.
	//////////////////////////////////////////////////////////////////////////
	bool GetDataAt( unsigned int _Column, unsigned int _Row, std::string& _Output );

	//////////////////////////////////////////////////////////////////////////
	// Set data in the table at position [_Column, _Row].
	// If
	//////////////////////////////////////////////////////////////////////////
	void SetDataAt( unsigned int _Column, unsigned int _Row, std::string& _Data );

	//////////////////////////////////////////////////////////////////////////
	// Gets the number of rows.
	// NOTE: There is no GetNumColumns function because the number of columns
	// can vary per row.
	//////////////////////////////////////////////////////////////////////////
	unsigned int GetNumRows();

	//////////////////////////////////////////////////////////////////////////
	// Returns the number of columns at a certain row.
	//////////////////////////////////////////////////////////////////////////
	unsigned int GetNumColumnsAtRow( unsigned int _Row );

	//////////////////////////////////////////////////////////////////////////
	// Utilizes both GetNumRows and GetNumColumnsAtRow in order to find the
	// total number of entries in the table.
	//////////////////////////////////////////////////////////////////////////
	unsigned int GetNumEntries();

	//////////////////////////////////////////////////////////////////////////
	// Clear the table.
	//////////////////////////////////////////////////////////////////////////
	void Clear();

	//////////////////////////////////////////////////////////////////////////
	// Check whether the table is empty.
	//////////////////////////////////////////////////////////////////////////
	bool IsEmpty();

	//////////////////////////////////////////////////////////////////////////
	// Export the CSV table to a file.
	//////////////////////////////////////////////////////////////////////////
	bool Export( const char* _File, bool _AllowIfEmpty = true );
private:
	std::vector<std::vector<std::string>> m_Data;
};

extern LkCSVParser* g_CSVParser;

}

}

#endif