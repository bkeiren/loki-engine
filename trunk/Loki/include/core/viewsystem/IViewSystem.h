#pragma once

#ifndef IVIEWSYSTEM_H
#define IVIEWSYSTEM_H

namespace loki
{

class IView;

class IViewSystem
{
public:
	IViewSystem();
	virtual ~IViewSystem() = 0;

	//////////////////////////////////////////////////////////////////////////
	// Finds a view by name. Returns NULL if it doesn't exist.
	//////////////////////////////////////////////////////////////////////////
	virtual IView* FindViewByName( const char* _ViewName ) const = 0;

	//////////////////////////////////////////////////////////////////////////
	// Creates a new view. Returns NULL of _ViewName is already in use.
	//////////////////////////////////////////////////////////////////////////
	virtual IView* CreateView( const char* _ViewName ) = 0;

	//////////////////////////////////////////////////////////////////////////
	// Destroys the given view. If
	//////////////////////////////////////////////////////////////////////////
	virtual void DestroyView( const char* _ViewName ) = 0;

	//////////////////////////////////////////////////////////////////////////
	// Sets the currently active view from _View.
	//////////////////////////////////////////////////////////////////////////
	virtual void SetActiveView( IView* _View ) = 0;

	//////////////////////////////////////////////////////////////////////////
	// Sets the currently active view by name. If there is no view with
	// the passed name, returns false. Returns true otherwise. Note that
	// the active view is not modified if _ViewName can not be found.
	//////////////////////////////////////////////////////////////////////////
	virtual bool SetActiveView( const char* _ViewName ) = 0;

	//////////////////////////////////////////////////////////////////////////
	// Returns the currently active view.
	//////////////////////////////////////////////////////////////////////////
	virtual IView* GetActiveView() const = 0;
private:
};

extern IViewSystem* g_ViewSystem;

}

#endif